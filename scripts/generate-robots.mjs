#!/usr/bin/env node

/**
 * Generates public/robots.txt at build time.
 *
 * WHY THIS EXISTS:
 * Ensures robots.txt is always present as a static file in the build output,
 * providing reliable serving regardless of the deployment platform.
 * The route handler (app/robots.txt/route.ts) serves as a fallback.
 */

import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, "..");
const localesConfig = JSON.parse(
  readFileSync(join(rootDir, "config", "locales.json"), "utf8"),
);
const robotsPolicy = JSON.parse(
  readFileSync(join(rootDir, "config", "robots-policy.json"), "utf8"),
);
const SUPPORTED_LOCALES = Object.keys(localesConfig.locales);

// Get site URL from environment or use default
const siteUrl =
  process.env.NEXT_PUBLIC_SITE_URL ||
  process.env.NEXT_PUBLIC_VERCEL_URL ||
  "https://www.esdeveniments.cat";

// Normalize URL (remove trailing slash, ensure https)
const normalizedSiteUrl = siteUrl.replace(/\/$/, "").replace(/^http:/, "https:");

// Detect non-production hosts (staging, PR previews, dev) — these must not
// be indexed. GSC reported ~7,800 staging URLs leaking into Google's index
// because robots.txt allowed everything and no X-Robots-Tag was emitted.
//
// Default-deny: anything not on the production allowlist below is treated as
// non-production. Substring checks (e.g. `pr-`) silently fail if Coolify's
// PR-preview URL template changes.
//
// KEEP IN SYNC WITH `utils/production-host.ts` (runtime copy).
const PRODUCTION_HOSTS = new Set([
  "www.esdeveniments.cat",
  "esdeveniments.cat",
]);
let isNonProductionHost = true;
try {
  isNonProductionHost = !PRODUCTION_HOSTS.has(
    new URL(normalizedSiteUrl).hostname.toLowerCase(),
  );
} catch {
  // Malformed URL → treat as non-production (safer default).
  isNonProductionHost = true;
}

/**
 * robots.txt configuration — shared with app/robots.txt/route.ts via
 * config/robots-policy.json and config/locales.json.
 */
const CRAWL_ALLOW = robotsPolicy.crawlAllow;
const CRAWL_DISALLOW = [
  ...robotsPolicy.crawlDisallowBase,
  ...robotsPolicy.crawlDisallowLocalized.flatMap((path) => [
    path,
    ...SUPPORTED_LOCALES.map((locale) => `/${locale}${path}`),
  ]),
];

const robotsConfig = {
  rules: [
    // Default rules for all crawlers (including search engines)
    { userAgent: "*", allow: CRAWL_ALLOW, disallow: CRAWL_DISALLOW },
    // AI agent crawlers (browsing/search + training). A crawler obeys only its
    // most specific group, so this group repeats the `*` paths; an allow-only
    // group would let them crawl /api/.
    {
      userAgent: robotsPolicy.allowedAiAgents,
      allow: CRAWL_ALLOW,
      disallow: CRAWL_DISALLOW,
    },
    // Non-vendor data harvesters with no direct end-user agent value.
    ...robotsPolicy.blockedAgents.map((userAgent) => ({
      userAgent,
      disallow: ["/"],
    })),
  ],
  // One index: it lists every child sitemap, so naming them too only
  // made crawlers fetch each one twice.
  sitemaps: [`${normalizedSiteUrl}/sitemap.xml`],
  host: normalizedSiteUrl,
};

// On non-production hosts (staging, PR previews), block all crawlers and
// strip sitemaps. Disallow-all on User-Agent: * fully blocks indexing.
if (isNonProductionHost) {
  robotsConfig.rules = [
    {
      userAgent: "*",
      disallow: ["/"],
    },
  ];
  robotsConfig.sitemaps = [];
}

function generateRobotsTxt() {
  const lines = [];

  // Add generation timestamp
  lines.push(`# Generated by scripts/generate-robots.mjs at ${new Date().toISOString()}`);
  lines.push(`# Site URL: ${normalizedSiteUrl}`);
  lines.push("");

  // Add rules
  for (const rule of robotsConfig.rules) {
    for (const userAgent of [rule.userAgent].flat()) {
      lines.push(`User-Agent: ${userAgent}`);
    }

    if (rule.allow) {
      for (const path of rule.allow) {
        lines.push(`Allow: ${path}`);
      }
    }

    if (rule.disallow) {
      for (const path of rule.disallow) {
        lines.push(`Disallow: ${path}`);
      }
    }

    lines.push("");
  }

  // Add host
  lines.push(`Host: ${robotsConfig.host}`);
  lines.push("");

  // Add sitemaps
  for (const sitemap of robotsConfig.sitemaps) {
    lines.push(`Sitemap: ${sitemap}`);
  }

  // Content Signals
  lines.push("");
  lines.push("# Content Signals — AI usage preferences");
  lines.push(`Content-Signal: ${robotsPolicy.contentSignal}`);

  // Schema feed directive
  lines.push("");
  lines.push("# Schema feed for structured data discovery");
  lines.push(`schemamap: ${normalizedSiteUrl}/openapi.json`);

  return lines.join("\n");
}

// Generate and write robots.txt
const robotsTxt = generateRobotsTxt();
const outputPath =
  process.env.ROBOTS_OUTPUT_PATH || join(rootDir, "public", "robots.txt");

writeFileSync(outputPath, robotsTxt, "utf-8");

console.log(`✅ Generated ${outputPath}`);
console.log(`   Site URL: ${normalizedSiteUrl}`);
const countAgents = (rules) => rules.flatMap((r) => [r.userAgent].flat()).length;
const blocked = countAgents(robotsConfig.rules.filter((r) => r.disallow && !r.allow));
const allowed = countAgents(robotsConfig.rules.filter((r) => r.allow));
console.log(`   User-agents: ${allowed} allowed, ${blocked} blocked`);
